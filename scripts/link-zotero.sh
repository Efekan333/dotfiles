#!/usr/bin/env bash
# Zotero profile dir has a random name → stow can't target it. Symlink tracked files into the
# Default=1 profile (Zotero's profiles.ini has no [Install…] section, unlike Zen).
set -euo pipefail
src="$(cd "$(dirname "$0")/.." && pwd)/zotero"
ini=~/.zotero/zotero/profiles.ini
[[ -f $ini ]] || { echo "no Zotero profile yet, skipping"; exit 0; }
prof=~/.zotero/zotero/$(awk -F= '/^\[Profile/{p=""} /^Path=/{p=$2} /^Default=1/{print p; exit}' "$ini")
mkdir -p "$prof/chrome"
ln -sfn "$src/user.js" "$prof/user.js"
for f in userChrome.css palette-vars.css; do
  ln -sfn "$src/chrome/$f" "$prof/chrome/$f"
done
# Reader/note-editor iframes are content docs (resource://zotero/…) → need userContent.css, and @import
# isn't allowed inside @-moz-document → generate it (not tracked). Re-run after editing palette-vars.css.
{ echo '/* GENERATED by scripts/link-zotero.sh from palette-vars.css — edit that instead. */'
  echo '@-moz-document url-prefix("resource://zotero/") {'
  cat "$src/chrome/palette-vars.css"
  echo '  body { font-family: "Rice Mono" !important; }'
  echo '  .toolbar #numPages div { position: static !important; white-space: nowrap; } /* absolute + JS-measured width overflows with mono */'
  echo '}'; } > "$prof/chrome/userContent.css"
echo "linked into $prof"
